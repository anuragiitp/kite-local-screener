/**
 * Generates src/screener/mfCategoryData.js, the bundled fallback for the in-app "Update AUM & categories":
 * SEBI category per Kite direct-growth fund (AMFI NAVAll.txt), IDCW/bonus ISINs, and AUM (Coin).
 * Run: node scripts/generate-mf-categories.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import { AMFI_URL, buildReference, fetchCoinAum, parseCsvLine } from '../src/screener/mfReference.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(__dirname, '../src/screener/mfCategoryData.js');
const KITE_URL = 'https://api.kite.trade/mf/instruments';

async function getText(url) {
  const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

const [kiteCsv, amfi] = await Promise.all([getText(KITE_URL), getText(AMFI_URL)]);

let coin;
try {
  coin = await fetchCoinAum(getText);
} catch (err) {
  // Keep the previous snapshot rather than wiping AUM when Coin's bundle layout changes.
  console.warn(`AUM: ${err.message}; keeping the previous snapshot`);
  const prev = await import(pathToFileURL(OUT).href).catch(() => ({}));
  coin = { aum: prev.MF_AUM || {}, date: prev.MF_AUM_DATE || '' };
}

const kiteLines = kiteCsv.trim().split(/\r?\n/);
const head = parseCsvLine(kiteLines[0]);
const col = (n) => head.indexOf(n);
const funds = [];
kiteLines.slice(1).forEach((line) => {
  const c = parseCsvLine(line);
  if (c[col('plan')] !== 'direct' || c[col('dividend_type')] !== 'growth') return;
  funds.push({ isin: c[col('tradingsymbol')], name: c[col('name')], schemeType: c[col('scheme_type')] });
});

const ref = buildReference(funds, amfi, coin);

const body = `// Generated by scripts/generate-mf-categories.mjs on ${new Date().toISOString().slice(0, 10)} (Kite mf/instruments + AMFI NAVAll.txt + Coin). Do not edit.
export const MF_CATEGORIES = ${JSON.stringify(ref.categories)};

export const MF_CATEGORY_BY_ISIN = ${JSON.stringify(ref.byIsin)};

// Listed by Kite as direct growth, but AMFI names them IDCW / bonus plans.
export const MF_NOT_GROWTH = ${JSON.stringify(ref.notGrowth)};

// AUM in ₹ crore from Coin, NAV date ${ref.aumDate || 'unknown'}.
export const MF_AUM_DATE = ${JSON.stringify(ref.aumDate)};
export const MF_AUM = ${JSON.stringify(ref.aum)};
`;
fs.writeFileSync(OUT, body);

const { stats } = ref;
console.log(`funds ${stats.funds}, AMFI matched ${stats.amfiMatched}, Kite fallback ${stats.fallback}, not growth ${stats.notGrowth}, AUM ${stats.aum} (${ref.aumDate}), ${(body.length / 1024).toFixed(0)} KB`);
const counts = {};
Object.values(ref.byIsin).forEach((i) => {
  const k = `${ref.categories[i].group} / ${ref.categories[i].label}`;
  counts[k] = (counts[k] || 0) + 1;
});
Object.entries(counts).sort().forEach(([k, n]) => console.log(`${String(n).padStart(5)}  ${k}`));
const byIsinName = new Map(funds.map((f) => [f.isin, f]));
Object.entries(ref.byIsin)
  .filter(([, i]) => ref.categories[i].group === 'Other' && ref.categories[i].label === 'Other')
  .forEach(([isin]) => console.log(`  unclassified: ${isin} ${byIsinName.get(isin).name} [${byIsinName.get(isin).schemeType}]`));
